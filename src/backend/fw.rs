//! Firmware-reference backend: the realization that produces documentation and
//! headers for driver / firmware developers, so the hardware-software interface
//! stays in sync with the PSS model.

use super::Backend;
use super::BackendOptions;
use crate::engine::Scenario;
use crate::error::PssResult;
use crate::ir::{Field, Model, TypeCategory};

pub struct FwBackend;

impl Backend for FwBackend {
    fn name(&self) -> &'static str {
        "fw"
    }

    fn description(&self) -> &'static str {
        "Firmware/driver reference: interface map, address map and headers"
    }

    fn emit(&self, model: &Model, scenario: &Scenario, _opts: &BackendOptions) -> PssResult<String> {
        let mut s = String::new();
        s.push_str("# Firmware Reference — generated by Satya\n\n");
        s.push_str(&format!("- Root action: `{}`\n", scenario.root_action));
        s.push_str(&format!(
            "- Top component: `{}`\n",
            scenario.top_component.as_deref().unwrap_or("<none>")
        ));
        s.push_str(&format!("- Steps: {}\n\n", scenario.steps.len()));

        // ---- Interface / register map ----
        s.push_str("## Interface map\n\n");
        s.push_str("Memory-mapped interface described by the model.\n\n");
        let names = super::ordered_type_keys(model);
        for name in &names {
            let t = &model.types[name];
            s.push_str(&format!("### `{}`\n\n", name));
            s.push_str("| Field | Type | Width | Access |\n|---|---|---|---|\n");
            for f in &t.fields {
                s.push_str(&format!(
                    "| `{}` | `{}` | {} | {} |\n",
                    f.name,
                    f.type_name,
                    f.bits.map(|b| format!("{} bits", b)).unwrap_or_else(|| "—".into()),
                    match f.kind {
                        crate::ir::FieldKind::Rand => "r/w",
                        _ => "r/w",
                    }
                ));
            }
            if t.fields.is_empty() {
                s.push_str("| _(none)_ | | | |\n");
            }
            s.push('\n');
        }

        // ---- Address map ----
        s.push_str("## Address map\n\n");
        if scenario.addr_regions.is_empty() {
            s.push_str("_No address regions were declared by the model._\n\n");
        } else {
            s.push_str("| Region | Base | Size |\n|---|---|---|\n");
            for (n, base, size) in &scenario.addr_regions {
                s.push_str(&format!("| `{}` | 0x{:X} | 0x{:X} |\n", n, base, size));
            }
            s.push('\n');
        }
        let allocated: Vec<_> = scenario
            .steps
            .iter()
            .flat_map(|st| st.flow.iter().map(move |fr| (st.index, fr)))
            .filter(|(_, fr)| fr.addr.is_some())
            .collect();
        if !allocated.is_empty() {
            s.push_str("### Allocated objects\n\n| Step | Object | Type | Address |\n|---|---|---|---|\n");
            for (idx, fr) in &allocated {
                s.push_str(&format!(
                    "| {} | `{}` | `{}` | 0x{:X} |\n",
                    idx,
                    fr.field,
                    fr.type_name,
                    fr.addr.unwrap()
                ));
            }
            s.push('\n');
        }

        // ---- Scenario ----
        s.push_str("## Scenario\n\n");
        s.push_str("| # | Action | Component | Mode | Fields |\n|---|---|---|---|---|\n");
        for st in &scenario.steps {
            s.push_str(&format!(
                "| {} | `{}` | `{}` | {} | {} |\n",
                st.index,
                st.action,
                st.component,
                st.mode.label(),
                st.fields
                    .iter()
                    .map(|(k, v)| format!("{}={}", k, v))
                    .collect::<Vec<_>>()
                    .join(", ")
            ));
        }
        s.push('\n');

        // ---- Generated header ----
        s.push_str("## Generated header\n\n");
        s.push_str("```c\n");
        s.push_str("/* generated by Satya — driver interface */\n");
        s.push_str("#ifndef SATYA_FW_INTERFACE_H\n#define SATYA_FW_INTERFACE_H\n\n");
        s.push_str("#include <stdint.h>\n\n");
        for name in &names {
            let t = &model.types[name];
            s.push_str(&format!("typedef struct {{\n"));
            for f in &t.fields {
                s.push_str(&format!("    {} {};\n", c_type(model, f), sanitize(&f.name)));
            }
            if t.fields.is_empty() {
                s.push_str("    uint8_t _empty;\n");
            }
            s.push_str(&format!("}} {}_t;\n\n", sanitize(&t.name)));
        }
        for (n, base, size) in &scenario.addr_regions {
            s.push_str(&format!(
                "#define {}_BASE 0x{:X}ULL\n#define {}_SIZE 0x{:X}ULL\n",
                sanitize(n).to_uppercase(),
                base,
                sanitize(n).to_uppercase(),
                size
            ));
        }
        s.push('\n');
        for (idx, fr) in &allocated {
            s.push_str(&format!(
                "#define {}_ADDR 0x{:X}ULL  /* step {}, {} */\n",
                sanitize(&format!("{}_{}", fr.type_name, fr.obj_id.unwrap_or(0))).to_uppercase(),
                fr.addr.unwrap(),
                idx,
                fr.field
            ));
        }
        s.push_str("\n#endif /* SATYA_FW_INTERFACE_H */\n");
        s.push_str("```\n");
        Ok(s)
    }
}

fn c_type(model: &Model, f: &Field) -> String {
    match &f.category {
        TypeCategory::Scalar => match f.bits {
            Some(n) if n <= 8 => "uint8_t".into(),
            Some(n) if n <= 16 => "uint16_t".into(),
            Some(n) if n <= 32 => "uint32_t".into(),
            Some(_) => "uint64_t".into(),
            None => "int32_t".into(),
        },
        TypeCategory::Enum(_) => "uint32_t".into(),
        TypeCategory::Struct(t) => format!("{}_t", sanitize(&model.type_leaf(t))),
        TypeCategory::Handle => "uint64_t".into(),
        TypeCategory::Component(_) => "void *".into(),
        TypeCategory::Unknown => "int64_t".into(),
    }
}

fn sanitize(s: &str) -> String {
    s.chars()
        .map(|c| if c.is_ascii_alphanumeric() || c == '_' { c } else { '_' })
        .collect()
}

//! Post-silicon / bench backend: turns the same scenario into an
//! interface-level sequence that a bench controller can run against silicon,
//! bridging the device's functional interfaces to external ones (JTAG, SPI,
//! I2C, UART, …).
//!
//! The output is a runnable Python driver with the sequence embedded and a
//! pluggable `Transport` so a real bench adapter can be dropped in.

use super::Backend;
use super::BackendOptions;
use crate::engine::{Scenario, StepMode};
use crate::error::PssResult;
use crate::ir::Model;

pub struct BenchBackend;

impl Backend for BenchBackend {
    fn name(&self) -> &'static str {
        "bench"
    }

    fn description(&self) -> &'static str {
        "Post-silicon bench sequence (JTAG/SPI/I2C transport)"
    }

    fn emit(&self, _model: &Model, scenario: &Scenario, _opts: &BackendOptions) -> PssResult<String> {
        let mut s = String::new();
        s.push_str("#!/usr/bin/env python3\n");
        s.push_str("\"\"\"\n");
        s.push_str("Generated by Satya — post-silicon / bench realization.\n\n");
        s.push_str(&format!("Root action  : {}\n", scenario.root_action));
        s.push_str(&format!(
            "Top component: {}\n",
            scenario.top_component.as_deref().unwrap_or("<none>")
        ));
        s.push_str("\nThe same scenario that drives simulation is replayed here over an\n");
        s.push_str("external transport (JTAG / SPI / I2C / UART), so pre-silicon and\n");
        s.push_str("post-silicon testing share one source of truth.\n");
        s.push_str("\"\"\"\n\n");
        s.push_str("import json\nimport sys\nimport time\n\n");

        s.push_str("# Default external interface for this sequence.\n");
        s.push_str("INTERFACE = \"jtag\"  # jtag | spi | i2c | uart | pcie | usb | eth\n\n");

        // Sequence as data.
        s.push_str("SEQUENCE = [\n");
        for step in &scenario.steps {
            let ops = ops_for(step);
            s.push_str("    {\n");
            s.push_str(&format!("        \"index\": {},\n", step.index));
            s.push_str(&format!("        \"action\": \"{}\",\n", escape(&step.action)));
            s.push_str(&format!("        \"component\": \"{}\",\n", escape(&step.component)));
            s.push_str(&format!("        \"mode\": \"{}\",\n", mode_str(step.mode)));
            s.push_str(&format!("        \"group\": {},\n", step.group));
            s.push_str(&format!("        \"unresolved\": {},\n", py_bool(step.unresolved)));
            s.push_str("        \"fields\": {");
            let f: Vec<String> = step
                .fields
                .iter()
                .map(|(k, v)| format!("\"{}\": {}", escape(k), v))
                .collect();
            s.push_str(&f.join(", "));
            s.push_str("},\n");
            s.push_str("        \"operations\": [\n");
            for op in &ops {
                s.push_str(&format!("            {},\n", op));
            }
            s.push_str("        ],\n");
            s.push_str("    },\n");
        }
        s.push_str("]\n\n");

        s.push_str(r#"
class Transport:
    """Adapter to the device under test. Subclass and implement for a real
    bench (e.g. a JTAG/SPI bridge, a USB-TMC instrument, or an ATE API)."""

    def __init__(self, interface):
        self.interface = interface

    def execute(self, action):
        """Run a leaf action on the target."""
        raise NotImplementedError

    def write(self, address, value):
        """Write a value to a memory-mapped address."""
        raise NotImplementedError

    def read(self, address):
        """Read a memory-mapped address."""
        raise NotImplementedError


class LoggingTransport(Transport):
    """Dry-run transport: prints what would happen."""

    def execute(self, action):
        print("  execute %s" % action)

    def write(self, address, value):
        if isinstance(value, dict):
            payload = ", ".join("%s=%s" % (k, v) for k, v in value.items())
            print("  write   0x%X <- {%s}" % (address, payload))
        else:
            print("  write   0x%X <- 0x%X" % (address, value & 0xFFFFFFFFFFFFFFFF))

    def read(self, address):
        print("  read    0x%X" % address)
        return 0


def run(transport, sequence, verbose=True):
    failures = 0
    for step in sequence:
        if verbose:
            print("[%3d] %s @ %s (%s)" % (
                step["index"], step["action"], step["component"], step["mode"]))
        if step["unresolved"]:
            print("      !! unresolved action, skipping")
            failures += 1
            continue
        for op in step["operations"]:
            if op["op"] == "write":
                transport.write(op["address"], op["value"])
            elif op["op"] == "read":
                transport.read(op["address"])
            else:
                transport.execute(op.get("action", step["action"]))
    return failures


def main(argv):
    transport = LoggingTransport(INTERFACE)
    if len(argv) > 1 and argv[1] == "--json":
        print(json.dumps(SEQUENCE, indent=2))
        return 0
    failures = run(transport, SEQUENCE)
    print("Satya bench sequence complete: %d steps, %d unresolved" %
          (len(SEQUENCE), failures))
    return 1 if failures else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
"#);
        Ok(s)
    }
}

/// Build the JSON operations for one step.
fn ops_for(step: &crate::engine::Step) -> Vec<String> {
    let mut out = Vec::new();
    for fr in &step.flow {
        if let Some(addr) = fr.addr {
            // A flow object: write its fields into the memory map.
            let mut payload: Vec<String> = Vec::new();
            for (k, v) in &step.fields {
                if k.starts_with(&format!("{}.", fr.field)) {
                    payload.push(format!("\"{}\": {}", escape(k), v));
                }
            }
            let data = if payload.is_empty() {
                "{}".to_string()
            } else {
                format!("{{{}}}", payload.join(", "))
            };
            out.push(format!(
                "{{\"op\": \"write\", \"address\": {}, \"value\": {}, \"object\": \"{}\"}}",
                addr,
                data,
                escape(&fr.field)
            ));
        }
    }
    if out.is_empty() {
        out.push(format!(
            "{{\"op\": \"execute\", \"action\": \"{}\"}}",
            escape(&step.action)
        ));
    }
    out
}

fn py_bool(b: bool) -> &'static str {
    if b {
        "True"
    } else {
        "False"
    }
}

fn mode_str(m: StepMode) -> &'static str {
    match m {
        StepMode::Sequential => "sequential",
        StepMode::Parallel => "parallel",
        StepMode::Schedule => "schedule",
        StepMode::Atomic => "atomic",
        StepMode::Select => "select",
    }
}

fn escape(s: &str) -> String {
    s.replace('\\', "\\\\").replace('"', "\\\"")
}

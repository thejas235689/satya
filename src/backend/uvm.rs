//! UVM/SystemVerilog backend: turns the solved scenario into UVM sequence
//! classes plus a top-level virtual sequence. This is the "sequence generator"
//! role that tools such as InFact play — the difference being that here the
//! sequences are one *output* of a backend-agnostic scenario, not the model's
//! reason for existing.

use std::collections::BTreeSet;

use super::{render_sv, Backend, BackendOptions};
use crate::engine::{Scenario, Step, StepMode};
use crate::error::PssResult;
use crate::ir::{Action, FieldKind, Model, TypeCategory};

pub struct UvmBackend;

impl Backend for UvmBackend {
    fn name(&self) -> &'static str {
        "uvm"
    }

    fn description(&self) -> &'static str {
        "UVM/SystemVerilog stimulus sequences"
    }

    fn emit(&self, model: &Model, scenario: &Scenario, opts: &BackendOptions) -> PssResult<String> {
        let top_seq = opts
            .top_sequence_name
            .clone()
            .unwrap_or_else(|| "satya_top_seq".to_string());

        let mut s = String::new();
        s.push_str("// -----------------------------------------------------------------------------\n");
        s.push_str("// Generated by Satya — portable test-stimulus engine\n");
        s.push_str(&format!("// Root action : {}\n", scenario.root_action));
        s.push_str(&format!(
            "// Top component: {}\n",
            scenario.top_component.as_deref().unwrap_or("<none>")
        ));
        s.push_str("// Backend      : uvm (SystemVerilog)\n");
        s.push_str("// -----------------------------------------------------------------------------\n\n");
        s.push_str("`ifndef SATYA_GENERATED_SV\n`define SATYA_GENERATED_SV\n\n");
        s.push_str("import uvm_pkg::*;\n`include \"uvm_macros.svh\"\n\n");

        // Emit one sequence per distinct action used in the schedule.
        let mut emitted: BTreeSet<String> = BTreeSet::new();
        for step in &scenario.steps {
            if step.unresolved || !emitted.insert(step.action.clone()) {
                continue;
            }
            if let Some(action) = model.action(&step.action) {
                emit_action_sequence(&mut s, model, action, step, opts.uvm_factory);
            }
        }

        emit_top_sequence(&mut s, &top_seq, &scenario.steps, opts.uvm_factory);

        s.push_str("\n`endif // SATYA_GENERATED_SV\n");
        Ok(s)
    }
}

fn emit_action_sequence(
    s: &mut String,
    model: &Model,
    action: &Action,
    step: &Step,
    factory: bool,
) {
    let cls = format!("{}_seq", action.name);
    s.push_str(&format!("// Action: {} (component {})\n", action.name, step.component));
    s.push_str(&format!(
        "class {} extends uvm_sequence #(uvm_sequence_item);\n",
        cls
    ));
    if factory {
        s.push_str(&format!("  `uvm_object_utils({})\n", cls));
    } else {
        s.push_str(&format!("  `uvm_object_utils({})\n", cls));
    }
    s.push('\n');

    // Randomisable / flow fields.
    for f in &action.fields {
        let decl = field_decl(model, f);
        if let Some(d) = decl {
            s.push_str(&format!("  {}\n", d));
        }
    }
    s.push('\n');

    s.push_str(&format!(
        "  function new(string name = \"{}\");\n    super.new(name);\n  endfunction\n\n",
        cls
    ));

    // Constraints.
    if !action.constraints.is_empty() {
        s.push_str(&format!("  constraint {}_c {{\n", action.name));
        for c in &action.constraints {
            s.push_str(&format!("    {};\n", render_sv(&c.expr)));
        }
        s.push_str("  }\n\n");
    }

    // A comment recording the reference solution Satya solved.
    if !step.fields.is_empty() {
        let vals: Vec<String> = step
            .fields
            .iter()
            .map(|(k, v)| format!("{}={}", k, v))
            .collect();
        s.push_str(&format!(
            "  // Reference solution solved by Satya: {}\n\n",
            vals.join(", ")
        ));
    }

    // body()
    s.push_str("  virtual task body();\n");
    s.push_str(&format!(
        "    `uvm_info(\"{}\", \"executing action {}\", UVM_MEDIUM)\n",
        cls, action.name
    ));
    for (k, v) in &step.fields {
        if !k.contains('.') {
            s.push_str(&format!(
                "    `uvm_info(\"{}\", $sformatf(\"  {} = {}\"), UVM_HIGH)\n",
                cls, k, v
            ));
        }
    }
    // Translate the action's `exec body`, if present.
    if let Some(exec) = action.execs.iter().find(|e| e.kind == "body") {
        if !exec.stmts.is_empty() {
            s.push_str("    // exec body (translated from the PSS model)\n");
            for st in &exec.stmts {
                emit_exec_sv(s, st, "    ");
            }
        }
    }
    s.push_str("  endtask\n");
    s.push_str("endclass\n\n");
}

/// Render an `exec` statement as SystemVerilog.
fn emit_exec_sv(s: &mut String, st: &crate::ast::ExecStmt, indent: &str) {
    use crate::ast::ExecStmt;
    match st {
        ExecStmt::Assign(path, rhs) => {
            s.push_str(&format!(
                "{}{} = {};\n",
                indent,
                path.segments.join("."),
                render_sv(rhs)
            ));
        }
        ExecStmt::Call(name, args) => {
            let a: Vec<String> = args.iter().map(render_sv).collect();
            s.push_str(&format!("{}{}({});\n", indent, name, a.join(", ")));
        }
        ExecStmt::If(c, then, els) => {
            s.push_str(&format!("{}if ({}) begin\n", indent, render_sv(c)));
            for st in then {
                emit_exec_sv(s, st, &format!("{}  ", indent));
            }
            s.push_str(&format!("{}end\n", indent));
            if !els.is_empty() {
                s.push_str(&format!("{}else begin\n", indent));
                for st in els {
                    emit_exec_sv(s, st, &format!("{}  ", indent));
                }
                s.push_str(&format!("{}end\n", indent));
            }
        }
        ExecStmt::Raw(text) => {
            s.push_str(&format!("{}// (untranslated) {}\n", indent, text));
        }
    }
}

fn field_decl(model: &Model, f: &crate::ir::Field) -> Option<String> {
    let rand = matches!(f.kind, FieldKind::Rand | FieldKind::Input | FieldKind::Output);
    let r = if rand { "rand " } else { "" };
    let comment = match f.kind {
        FieldKind::Input => "  // input flow object",
        FieldKind::Output => "  // output flow object",
        FieldKind::Lock => "  // lock claim",
        FieldKind::Share => "  // share claim",
        _ => "",
    };
    match &f.category {
        TypeCategory::Scalar => {
            let ty = match f.bits {
                Some(n) => format!("bit[{}]", n - 1),
                None => "int".to_string(),
            };
            Some(format!("{}{} {};{}", r, ty, f.name, comment))
        }
        TypeCategory::Enum(_) => Some(format!("{}int {};{}  // enum", r, f.name, comment)),
        TypeCategory::Struct(t) => {
            let _ = model;
            Some(format!("{}{} {};{}", r, t, f.name, comment))
        }
        TypeCategory::Handle => Some(format!("{} {};{}", f.type_name, f.name, comment)),
        TypeCategory::Component(_) => None,
        TypeCategory::Unknown => Some(format!("{} {};{}", f.type_name, f.name, comment)),
    }
}

fn emit_top_sequence(s: &mut String, top_seq: &str, steps: &[Step], _factory: bool) {
    s.push_str("// -----------------------------------------------------------------------------\n");
    s.push_str("// Top-level virtual sequence: replays the Satya schedule\n");
    s.push_str("// -----------------------------------------------------------------------------\n");
    s.push_str(&format!(
        "class {} extends uvm_sequence #(uvm_sequence_item);\n",
        top_seq
    ));
    s.push_str(&format!("  `uvm_object_utils({})\n\n", top_seq));
    s.push_str(&format!(
        "  function new(string name = \"{}\");\n    super.new(name);\n  endfunction\n\n",
        top_seq
    ));
    s.push_str("  virtual task body();\n");

    let mut i = 0usize;
    while i < steps.len() {
        let step = &steps[i];
        // Group a run of steps that share a parallel/schedule group id.
        if step.group > 0 && matches!(step.mode, StepMode::Parallel | StepMode::Schedule) {
            let g = step.group;
            let mut j = i;
            while j < steps.len() && steps[j].group == g {
                j += 1;
            }
            s.push_str(&format!(
                "    // parallel group {} ({} steps)\n    fork\n",
                g,
                j - i
            ));
            for k in i..j {
                s.push_str(&emit_start(&steps[k], "      "));
            }
            s.push_str("    join\n");
            i = j;
        } else {
            if step.mode == StepMode::Select {
                s.push_str("    // select: first viable branch\n");
            }
            s.push_str(&emit_start(step, "    "));
            i += 1;
        }
    }

    s.push_str("  endtask\n");
    s.push_str("endclass\n");
}

fn emit_start(step: &Step, indent: &str) -> String {
    if step.unresolved {
        return format!(
            "{}// TODO: unresolved action `{}` (define it in the PSS model)\n",
            indent, step.action
        );
    }
    format!(
        "{indent}begin\n{indent}  {cls} {var};\n{indent}  {var} = {cls}::type_id::create(\"{var}\");\n{indent}  {var}.start(m_sequencer);\n{indent}end\n",
        indent = indent,
        cls = format!("{}_seq", step.action),
        var = format!("s{}", step.index),
    )
}

//! Native-C backend: the "native mode" realization from the PSS-as-single-
//! source-of-truth flow, where the same scenario runs as C on a host processor
//! driving the rest of the SoC.
//!
//! The output is a single self-contained C file: type definitions, one function
//! per action, and a `main()` that replays the solved schedule.

use super::Backend;
use super::BackendOptions;
use crate::ast::{ExecStmt, Expr};
use crate::engine::{Scenario, Step, StepMode};
use crate::error::PssResult;
use crate::ir::{Action, Field, FieldKind, Model, TypeCategory};

pub struct CBackend;

impl Backend for CBackend {
    fn name(&self) -> &'static str {
        "c"
    }

    fn description(&self) -> &'static str {
        "Native C test harness (host-processor realization)"
    }

    fn emit(&self, model: &Model, scenario: &Scenario, _opts: &BackendOptions) -> PssResult<String> {
        let mut s = String::new();
        s.push_str("/* ---------------------------------------------------------------------------\n");
        s.push_str(" * Generated by Satya — native C realization\n");
        s.push_str(&format!(" * Root action  : {}\n", scenario.root_action));
        s.push_str(&format!(
            " * Top component: {}\n",
            scenario.top_component.as_deref().unwrap_or("<none>")
        ));
        s.push_str(" * Build        : cc -o scenario scenario.c\n");
        s.push_str(" * --------------------------------------------------------------------------- */\n\n");
        s.push_str("#include <stdio.h>\n#include <stdint.h>\n#include <string.h>\n\n");

        // Data types.
        s.push_str("/* ---- data types ---- */\n");
        let mut names: Vec<&String> = model.types.keys().collect();
        names.sort();
        for name in &names {
            let t = &model.types[*name];
            s.push_str(&format!("typedef struct {{\n"));
            for f in &t.fields {
                s.push_str(&format!("    {} {};\n", c_type(model, f), c_name(&f.name)));
            }
            if t.fields.is_empty() {
                s.push_str("    uint8_t _empty;\n");
            }
            s.push_str(&format!("}} {}_t;\n\n", sanitize(&t.name)));
        }

        // Address map comment.
        if !scenario.addr_regions.is_empty() {
            s.push_str("/* ---- address map ---- */\n");
            for (n, base, size) in &scenario.addr_regions {
                s.push_str(&format!(
                    "/* {} : base 0x{:x} size 0x{:x} */\n",
                    n, base, size
                ));
            }
            s.push('\n');
        }

        // Actions used by the schedule.
        let mut emitted: Vec<String> = Vec::new();
        for step in &scenario.steps {
            if step.unresolved || emitted.contains(&step.action) {
                continue;
            }
            emitted.push(step.action.clone());
            if let Some(action) = model.action(&step.action) {
                emit_action(&mut s, model, action, step);
            }
        }

        // main()
        s.push_str("int main(void) {\n");
        s.push_str(&format!(
            "    printf(\"Satya native scenario: {} (top {})\\n\");\n",
            scenario.root_action,
            scenario.top_component.as_deref().unwrap_or("-")
        ));
        let mut i = 0usize;
        while i < scenario.steps.len() {
            let step = &scenario.steps[i];
            if step.group > 0 && matches!(step.mode, StepMode::Parallel | StepMode::Schedule) {
                let g = step.group;
                let mut j = i;
                while j < scenario.steps.len() && scenario.steps[j].group == g {
                    j += 1;
                }
                s.push_str(&format!(
                    "    /* parallel group {} — a real harness would fork here */\n",
                    g
                ));
                for k in i..j {
                    s.push_str(&emit_step(&scenario.steps[k], "    "));
                }
                i = j;
            } else {
                s.push_str(&emit_step(step, "    "));
                i += 1;
            }
        }
        s.push_str("    printf(\"Satya: scenario complete (%d steps)\\n\", ");
        s.push_str(&format!("{});\n", scenario.steps.len()));
        s.push_str("    return 0;\n}\n");
        Ok(s)
    }
}

fn emit_action(s: &mut String, model: &Model, action: &Action, step: &Step) {
    let _ = step;
    s.push_str(&format!("/* ---- action: {} ---- */\n", action.name));
    s.push_str("typedef struct {\n");
    let mut any = false;
    for f in &action.fields {
        if matches!(f.category, TypeCategory::Component(_)) {
            continue;
        }
        s.push_str(&format!("    {} {};\n", c_type(model, f), c_name(&f.name)));
        any = true;
    }
    if !any {
        s.push_str("    uint8_t _empty;\n");
    }
    s.push_str(&format!("}} {}_t;\n\n", sanitize(&action.name)));

    s.push_str(&format!(
        "static void {}_run({}_t *self) {{\n",
        sanitize(&action.name),
        sanitize(&action.name)
    ));
    s.push_str(&format!(
        "    printf(\"{}\\n\");\n",
        action.name
    ));
    // Print scalar fields.
    for f in &action.fields {
        if matches!(f.category, TypeCategory::Component(_)) {
            continue;
        }
        if matches!(f.category, TypeCategory::Struct(_)) {
            continue;
        }
        s.push_str(&format!(
            "    printf(\"    {} = %lld\\n\", (long long)self->{});\n",
            f.name,
            c_name(&f.name)
        ));
    }
    // Translate the `body` exec block, if present.
    let field_names: Vec<String> = action.fields.iter().map(|f| f.name.clone()).collect();
    if let Some(exec) = action.execs.iter().find(|e| e.kind == "body") {
        for st in &exec.stmts {
            emit_exec_stmt(s, st, "    ", &field_names);
        }
    }
    s.push_str("}\n\n");
}

fn emit_step(step: &Step, indent: &str) -> String {
    if step.unresolved {
        return format!(
            "{}/* TODO: unresolved action `{}` */\n",
            indent, step.action
        );
    }
    let mut s = String::new();
    s.push_str(&format!(
        "{}/* step {}: {} @ {} */\n",
        indent, step.index, step.action, step.component
    ));
    s.push_str(&format!(
        "{}/*   fields: {} */\n",
        indent,
        step.fields
            .iter()
            .map(|(k, v)| format!("{}={}", k, v))
            .collect::<Vec<_>>()
            .join(" ")
    ));
    for fr in &step.flow {
        s.push_str(&format!(
            "{}/*   {} {} : {}{} */\n",
            indent,
            fr.direction,
            fr.field,
            fr.type_name,
            match fr.addr {
                Some(a) => format!(" @ 0x{:x}", a),
                None => String::new(),
            }
        ));
    }
    s.push_str(&format!("{}{{\n", indent));
    s.push_str(&format!(
        "{}    {}_t s{};\n{}    memset(&s{}, 0, sizeof(s{}));\n",
        indent,
        sanitize(&step.action),
        step.index,
        indent,
        step.index,
        step.index
    ));
    for (k, v) in &step.fields {
        if k.contains('.') {
            continue;
        }
        s.push_str(&format!(
            "{}    s{}.{} = {};\n",
            indent,
            step.index,
            c_name(k),
            v
        ));
    }
    s.push_str(&format!(
        "{}    {}_run(&s{});\n{}}}\n",
        indent,
        sanitize(&step.action),
        step.index,
        indent
    ));
    s
}

fn emit_exec_stmt(s: &mut String, st: &ExecStmt, indent: &str, fields: &[String]) {
    match st {
        ExecStmt::Assign(path, rhs) => {
            if contains_call(rhs) {
                // The right-hand side calls a foreign function that has no C
                // definition; keep it as a comment so the file still compiles.
                s.push_str(&format!(
                    "{}/* self->{} = {};  (foreign call) */\n",
                    indent,
                    c_path(path),
                    c_expr_self(rhs, fields)
                ));
            } else {
                s.push_str(&format!(
                    "{}self->{} = {};\n",
                    indent,
                    c_path(path),
                    c_expr_self(rhs, fields)
                ));
            }
        }
        ExecStmt::Call(name, args) => {
            let a: Vec<String> = args.iter().map(|x| c_expr_self(x, fields)).collect();
            s.push_str(&format!(
                "{}/* foreign call: {}({}) */\n",
                indent,
                name,
                a.join(", ")
            ));
        }
        ExecStmt::If(c, then, els) => {
            s.push_str(&format!("{}if ({}) {{\n", indent, c_expr_self(c, fields)));
            for st in then {
                emit_exec_stmt(s, st, &format!("{}    ", indent), fields);
            }
            s.push_str(&format!("{}}}", indent));
            if !els.is_empty() {
                s.push_str(" else {\n");
                for st in els {
                    emit_exec_stmt(s, st, &format!("{}    ", indent), fields);
                }
                s.push_str(&format!("{}}}", indent));
            }
            s.push('\n');
        }
        ExecStmt::Raw(_) => {}
    }
}

/// Render an expression for use inside an action function, prefixing field
/// references with `self->`.
fn c_expr_self(e: &Expr, fields: &[String]) -> String {
    match e {
        Expr::Path(p) => {
            let first = p.segments.first().cloned().unwrap_or_default();
            let base = c_path(p);
            if fields.iter().any(|f| *f == first) {
                format!("self->{}", base)
            } else {
                base
            }
        }
        Expr::Unary(op, x) => format!("({}{})", op, c_expr_self(x, fields)),
        Expr::Binary(op, a, b) => {
            let o = if op == "->" { "/* -> */" } else { op.as_str() };
            format!("({} {} {})", c_expr_self(a, fields), o, c_expr_self(b, fields))
        }
        Expr::Ternary(c, t, f) => format!(
            "({} ? {} : {})",
            c_expr_self(c, fields),
            c_expr_self(t, fields),
            c_expr_self(f, fields)
        ),
        Expr::Cast(_, x) => c_expr_self(x, fields),
        Expr::Call(f, args) => {
            let a: Vec<String> = args.iter().map(|x| c_expr_self(x, fields)).collect();
            format!("{}({})", f, a.join(", "))
        }
        Expr::Int(v) => v.to_string(),
        Expr::Bool(b) => if *b { "1" } else { "0" }.to_string(),
        _ => "0".to_string(),
    }
}

fn contains_call(e: &Expr) -> bool {
    match e {
        Expr::Call(_, _) | Expr::Method(_, _, _) => true,
        Expr::Unary(_, x) | Expr::Cast(_, x) => contains_call(x),
        Expr::Binary(_, a, b) => contains_call(a) || contains_call(b),
        Expr::Ternary(a, b, c) => contains_call(a) || contains_call(b) || contains_call(c),
        _ => false,
    }
}

fn c_path(p: &crate::ast::Path) -> String {
    p.segments
        .iter()
        .map(|s| c_name(s))
        .collect::<Vec<_>>()
        .join(".")
}

fn c_type(model: &Model, f: &Field) -> String {
    match &f.category {
        TypeCategory::Scalar => match f.bits {
            Some(n) if n <= 8 => "uint8_t".into(),
            Some(n) if n <= 16 => "uint16_t".into(),
            Some(n) if n <= 32 => "uint32_t".into(),
            Some(_) => "uint64_t".into(),
            None => "int32_t".into(),
        },
        TypeCategory::Enum(_) => "uint32_t".into(),
        TypeCategory::Struct(t) => format!("{}_t", sanitize(&model.type_leaf(t))),
        TypeCategory::Handle => "uint64_t".into(),
        TypeCategory::Component(_) => "void *".into(),
        TypeCategory::Unknown => "int64_t".into(),
    }
}

fn sanitize(s: &str) -> String {
    s.chars()
        .map(|c| if c.is_ascii_alphanumeric() || c == '_' { c } else { '_' })
        .collect()
}

fn c_name(s: &str) -> String {
    // C keywords and reserved-ish names get a suffix.
    let base = sanitize(s);
    match base.as_str() {
        "int" | "long" | "short" | "char" | "float" | "double" | "default" | "register"
        | "auto" | "signed" | "unsigned" | "union" | "enum" | "struct" | "switch" | "case"
        | "for" | "while" | "do" | "if" | "else" | "return" | "sizeof" | "typedef" | "static"
        | "const" | "volatile" | "extern" | "goto" | "continue" | "break" => format!("{}_", base),
        _ => base,
    }
}

// Keep FieldKind referenced for clarity of intent.
#[allow(dead_code)]
fn _k(k: FieldKind) -> FieldKind {
    k
}
